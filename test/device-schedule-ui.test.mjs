import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
test('schedule editor offers one-time date with explicit browser timezone',async()=> {
  const page=await readFile(new URL('../app/page.js',import.meta.url),'utf8')
  assert.match(page,/<option value="once">Specific date \(one-time\)<\/option>/)
  assert.match(page,/type="date" required/)
  assert.match(page,/Intl.DateTimeFormat\(\).resolvedOptions\(\).timeZone/)
  assert.match(page,/One-time · \{schedule.date\}/)
  assert.doesNotMatch(page,/player local time|Times use the player/)
})
// Source-level wiring checks supplement the production build, not browser interaction coverage.
test('device selection is only offered inside the publish dialog',async()=> {
  const page=await readFile(new URL('../app/page.js',import.meta.url),'utf8')
  assert.doesNotMatch(page,/Select all|Clear selection|className="select-device"/)
  assert.match(page,/<legend>Target devices<\/legend>/)
  assert.match(page,/deviceIds: selected/)
  assert.match(page,/!selected.length/)
})
test('dashboard screenshot link is developer-only while schedule viewer is available normally',async()=> {
  const page=await readFile(new URL('../app/page.js',import.meta.url),'utf8')
  assert.match(page,/\{developerMode && <a[^>]*href=\{`\/api\/devices\/screenshot/)
  assert.match(page,/<DeviceSchedule device=\{device\}/)
  assert.match(page,/<DeviceSnapshot device=\{device\}/)
})
test('schedule UI requires confirmation, revision and explicit read; handles unverified readback',async()=> {
  const ui=await readFile(new URL('../app/DeviceSchedule.js',import.meta.url),'utf8')
  assert.match(ui,/window\.confirm/)
  assert.match(ui,/confirmed: true, revision: data\.revision/)
  assert.match(ui,/result\.verified === true/)
  assert.match(ui,/View device schedule/)
  assert.match(ui,/Download schedule XML/)
  assert.match(ui,/Delete selected entry/)
  assert.match(ui,/<table className="device-schedule-table"/)
  assert.match(ui,/type="radio"/)
  assert.match(ui,/revision: data\.revision, entryIndex/)
  assert.match(ui,/selectedIndex === null/)
  assert.match(ui,/setSelectedIndex\(null\)/)
  assert.match(ui,/pending\.current\?\.abort/)
  assert.match(ui,/key=\{`\$\{device\.id\}:\$\{device\.ip\}`\}/)
})
test('schedule inspection has a labelled native dialog and responsive entry details', async()=> {
  const ui=await readFile(new URL('../app/DeviceSchedule.js',import.meta.url),'utf8')
  const css=await readFile(new URL('../app/schedule.css',import.meta.url),'utf8')
  const page=await readFile(new URL('../app/page.js',import.meta.url),'utf8')
  assert.match(ui,/aria-haspopup="dialog"/)
  assert.match(ui,/dialog\.current\?\.showModal\(\)/)
  assert.match(ui,/aria-labelledby=\{titleId\}/)
  assert.match(ui,/setOpen\(true\); act\('read'\)/)
  assert.match(ui,/className="entry-details"/)
  assert.match(ui,/Device timezone is unknown|device timezone is unknown/)
  assert.match(css,/@media \(max-width: 760px\)/)
  assert.match(css,/min-width: 0; table-layout: fixed/)
  assert.doesNotMatch(css,/min-width: 1000px/)
  assert.match(page,/<details className="device-controls-disclosure">/)
})
